CREATE OR REPLACE FUNCTION fn_net_pay(p_employee_id integer)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
DECLARE v_basic numeric(12,2); v_allow numeric(12,2); v_deduct numeric(12,2); v_net numeric(12,2);
BEGIN
 SELECT basic_salary,allowance,deduction INTO v_basic,v_allow,v_deduct FROM employees WHERE employee_id=p_employee_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown employee ID %',p_employee_id; END IF;
 v_net:=v_basic+v_allow-v_deduct;
 IF v_net<0 THEN RAISE EXCEPTION 'Computed net pay cannot be negative'; END IF;
 RETURN v_net;
END $$;

CREATE OR REPLACE PROCEDURE pr_process_payroll(p_month date)
LANGUAGE plpgsql AS $$
DECLARE r record; v_gross numeric(12,2); v_net numeric(12,2);
BEGIN
 IF p_month IS NULL OR EXTRACT(DAY FROM p_month)<>1 THEN RAISE EXCEPTION 'pay_month must be the first day of a month'; END IF;
 FOR r IN SELECT employee_id,basic_salary,allowance FROM employees WHERE active=true LOOP
  v_gross:=r.basic_salary+r.allowance;
  v_net:=fn_net_pay(r.employee_id);
  INSERT INTO payroll(employee_id,pay_month,gross_pay,net_pay)
  VALUES(r.employee_id,p_month,v_gross,v_net)
  ON CONFLICT(employee_id,pay_month) DO NOTHING;
 END LOOP;
END $$;

CREATE OR REPLACE FUNCTION trg_salary_audit_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.basic_salary IS DISTINCT FROM NEW.basic_salary THEN
  INSERT INTO salary_audit(employee_id,old_salary,new_salary)
  VALUES(NEW.employee_id,OLD.basic_salary,NEW.basic_salary);
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_salary_audit AFTER UPDATE OF basic_salary ON employees
FOR EACH ROW EXECUTE FUNCTION trg_salary_audit_fn();

CALL pr_process_payroll((date_trunc('month',CURRENT_DATE)-interval '1 month')::date);
CALL pr_process_payroll(date_trunc('month',CURRENT_DATE)::date);

CREATE OR REPLACE VIEW v_payroll_report AS
SELECT e.full_name,p.pay_month,p.gross_pay,p.net_pay
FROM payroll p JOIN employees e USING(employee_id);
SELECT * FROM v_payroll_report ORDER BY pay_month,full_name;

CREATE INDEX idx_payroll_pay_month ON payroll(pay_month);
EXPLAIN SELECT employee_id,gross_pay,net_pay FROM payroll
WHERE pay_month=(date_trunc('month',CURRENT_DATE))::date;

